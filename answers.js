window.searchDoctorLibrary = function (query) {
  const stop = new Set(["the","and","for","are","was","what","when","how","should","does","about","with","that","this","from","have","has","can","you","your","my","a","an","or","to","of","in","is","it","do","if","me","i","on"]);
  const norm = (s) => String(s || "").toLowerCase().replace(/[^a-z0-9/]+/g, " ").replace(/\s+/g, " ").trim();
  const q = norm(query);
  if (!q) return window.MY_DOCTOR_LIBRARY.map((a, i) => ({ a, score: 0, i }));
  const terms = q.split(" ").filter((t) => t.length > 1 && !stop.has(t));
  const scored = window.MY_DOCTOR_LIBRARY.map((a, i) => {
    const title = norm(a.title);
    const hay = norm(a.title + " " + a.keywords + " " + a.topic + " " + a.body.join(" "));
    let score = 0;
    if (title.includes(q) || hay.includes(q)) score += 12;
    for (const t of terms) {
      if (title.split(" ").includes(t)) score += 8;
      else if (title.includes(t)) score += 5;
      if ((" " + norm(a.keywords) + " ").includes(" " + t + " ")) score += 4;
      if (hay.includes(t)) score += 1;
    }
    // common phrase boosts
    if (/130\s*\/\s*72|130 over 72/.test(q) && a.id === "bp-numbers") score += 20;
    if (/911|emergency|chest pain|stroke/.test(q) && a.topic === "Emergencies") score += 6;
    return { a, score, i };
  });
  return scored.filter((x) => x.score > 0).sort((p, q2) => q2.score - p.score || p.i - q2.i);
};
